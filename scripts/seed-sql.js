#!/usr/bin/env node
/* node scripts/seed-sql.js > supabase/seed.sql
   Generates upserts for stores (from branches) and menu_items (from catalog())
   out of js/data.js — the same ids the site and HattorIA use. Never edit seed.sql by hand.
   Only items with a published price are seeded (the DB needs a price to charge). */
"use strict";
const B = require("../js/data.js");
const q = (v) => (v === null || v === undefined ? "null" : `'${String(v).replace(/'/g, "''")}'`);
const out = [];
out.push("-- Generated by scripts/seed-sql.js from js/data.js. Do not edit by hand.", "begin;");
B.branches.forEach((b, i) => {
  out.push(`insert into public.stores (id, name, whatsapp, address, sort) values (${q(b.id)}, ${q(b.name)}, ${q(b.whatsapp)}, ${q(b.address)}, ${i})
  on conflict (id) do update set name = excluded.name, whatsapp = excluded.whatsapp, address = coalesce(excluded.address, public.stores.address), sort = excluded.sort;`);
});
const cat = Object.values(B.catalog()).filter((i) => i.orderable);
cat.forEach((i) => {
  out.push(`insert into public.menu_items (id, name, kind, category, size, description, price, veg, sort) values (${q(i.id)}, ${q(i.name)}, ${q(i.kind)}, ${q(i.cat)}, ${q(i.size)}, ${q(i.desc)}, ${i.price}, ${i.veg}, ${i.sort})
  on conflict (id) do update set name = excluded.name, kind = excluded.kind, category = excluded.category, size = excluded.size, description = excluded.description, price = excluded.price, veg = excluded.veg, sort = excluded.sort;`);
});
out.push("commit;", "",
  "-- First owner: create the user in Supabase Auth (Dashboard → Authentication → Add user),",
  "-- then run, replacing the email:",
  "-- insert into public.staff (user_id, full_name, email, role)",
  "--   select id, 'Dueño Hattori', email, 'owner' from auth.users where email = 'OWNER_EMAIL_HERE';",
  "-- Everyone else is created from /admin → Equipo.");
console.log(out.join("\n"));
